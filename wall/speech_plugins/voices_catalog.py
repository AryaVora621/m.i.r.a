class VoicesCatalogPlugin(PluginBase):
    def __init__(self, ctx, cfg: PluginConfig) -> None:
        super().__init__(ctx, cfg)
        self.catalog: Optional[VoiceCatalog] = None

    def _models_dir(self) -> Path:
        base = expand_path(self.ctx.cfg_of("server.http")["base_dir"], self.ctx.paths)
        return base / "models"

    def start(self) -> None:
        self.catalog = VoiceCatalog(
            self._models_dir, rescan_s=lambda: self.cfg.rescan_s, featured=lambda: list(self.cfg.featured),
            agent_max_rtf=lambda: self.cfg.agent_max_rtf,
            rtf_file=lambda: expand_path(self.cfg.rtf_file, self.ctx.paths) if self.cfg.rtf_file else None,
            tts=lambda: self.ctx.get("tts", None))
        self.catalog.rescan()
        self.ctx.provide("voices", self.catalog)
        self.ctx.effect(self.catalog.flush_rtf, "voices rtf file")

    def status(self) -> dict:
        c = self.catalog
        return {"scans": c.scans if c else 0, "voices": len(c._entries) if c else 0}


