"""Plugin voices.catalog: every voice the mini can speak, with stable ids and friendly aliases (spec 2.9.3).

A pure scan of <base_dir>/models for vits-piper-* and kokoro-* directories. Piper facts come from the
model's own *.onnx.json; Kokoro names and counts come from the committed tables in
speech_plugins/voices/<model_dir>.json (generated by index_main from the ONNX metadata, never typed by hand).

FIXED: the three-voice near match limit, the exponential moving average weight of measured real-time
factors, the rtf file write interval, the benchmark sentence, the Kokoro language letters.
"""
