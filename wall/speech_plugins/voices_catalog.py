def _speaker_names(raw: str) -> list[str]:
    """Names out of an ONNX metadata string: a JSON list, or names split on commas, semicolons or newlines."""
    try:
        data = json.loads(raw)
        if isinstance(data, list):
            return [str(x) for x in data]
    except ValueError:
        pass
    cleaned = re.sub(r"[^\x20-\x7e\n]", "", raw)
    return [t.strip() for t in re.split(r"[,;\n]", cleaned) if t.strip()]


def index_main(models_dir, out_dir) -> dict[str, int]:
    """Write one speaker table per kokoro-* directory under models_dir into out_dir; returns {dir: voices}."""
    import onnxruntime
    result: dict[str, int] = {}
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    for d in sorted(Path(models_dir).glob("kokoro-*")):
        if not d.is_dir():
            continue
        onnx = next((p for p in sorted(d.glob("*.onnx")) if not p.name.startswith("voices")), None)
        if onnx is None:
            continue
        meta = onnxruntime.InferenceSession(str(onnx), providers=["CPUExecutionProvider"]).get_modelmeta().custom_metadata_map
        names = _speaker_names(meta.get("speaker_names", ""))
        count = int(re.sub(r"\D", "", meta.get("n_speakers", "")) or 0)
        if not names or len(names) != count:
            raise ValueError(f"{d.name}: {len(names)} speaker names but n_speakers is {count}")
        rate = int(re.sub(r"\D", "", meta.get("sample_rate", "")) or 24000)
        table = {"n_speakers": count, "sample_rate": rate, "speaker_names": names,
                 "source": "ONNX metadata_props speaker_names and n_speakers"}
        (out / f"{d.name}.json").write_text(json.dumps(table, indent=1) + "\n", encoding="utf-8")
        result[d.name] = count
    return result


def bench_main(models_dir, rtf_file, *, threads: int = 4, only: str = "", sentence: str = BENCH_SENTENCE,
               loader: Optional[Callable[[Path, int], Any]] = None, clock: Callable[[], float] = time.perf_counter,
               log: Callable[[str], None] = lambda s: None) -> dict[str, float]:
    """Render one sentence per usable voice and write the measured real-time factors to rtf_file."""
    from . import tts_kokoro, tts_piper

    def default_loader(path: Path, n: int):
        mod = tts_kokoro if tts_kokoro.handles(path) else tts_piper
        return mod.load_model(path, n, {})

    load = loader or default_loader
    catalog = VoiceCatalog(lambda: Path(models_dir), rtf_file=lambda: Path(rtf_file))
    results: dict[str, float] = {}
    cache: dict[str, Any] = {}
    for entry in catalog.list(include_unusable=False):
        if only and _norm(only) not in {_norm(a) for a in entry["aliases"]} and only != entry["id"]:
            continue
        path, sid = catalog.locate(entry)
        model = cache.get(path.name) or cache.setdefault(path.name, load(path, threads))
        t0 = clock()
        samples, rate = model.generate(sentence, sid, 1.0)
        elapsed = clock() - t0
        duration = len(samples) / rate
        if duration > 0:
            results[entry["id"]] = elapsed / duration
            log(f"{entry['id']}: rtf {results[entry['id']]:.2f}")
    catalog.set_rtf(results)
    return results


