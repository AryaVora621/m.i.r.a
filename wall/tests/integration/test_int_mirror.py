"""Integration: the legacy mirror (spec 2.5.6). A production-style core (from_file, mirror=True) regenerates
<cfgdir>/listen.env and <cfgdir>/legacy.args after boot and after every applied change, keeps the hand-written
listen.env once as listen.env.bak-adopt-<date>, and writes only under HOME. HOME is a temp dir."""
import json
import re
from pathlib import Path

from test_int_facade import Rig, cal_audio, ml, rig_factory  # noqa: F401
from mirakit.plugin import Edit


def kv(text):
    return dict(ln.split("=", 1) for ln in text.splitlines() if "=" in ln and not ln.startswith("#"))


def tokens(text):
    return [ln for ln in text.splitlines() if ln]


def mk(tmp_path, monkeypatch, **kw):
    cfgdir = tmp_path / "home" / ".config" / "mira"
    cfgdir.mkdir(parents=True)
    (cfgdir / "listen.env").write_text("MIRA_AGC_TARGET=0.07\nMIRA_SPEECH_URL=http://old.example\n")   # hand-written
    return Rig(tmp_path, monkeypatch, cal_audio(2.0), mode="file", **kw), cfgdir


def test_boot_writes_the_mirror_and_keeps_the_hand_written_env_once(tmp_path, monkeypatch):
    r, cfgdir = mk(tmp_path, monkeypatch)
    try:
        env = (cfgdir / "listen.env").read_text()
        assert env.startswith("# generated by mirakit from mira.json; edit with mira set")
        assert kv(env)["MIRA_AGC_TARGET"] == "0.05"                          # the file's (default) value, not the old hand edit
        bak = list(cfgdir.glob("listen.env.bak-adopt-*"))
        assert len(bak) == 1 and "old.example" in bak[0].read_text()
        assert re.fullmatch(r"listen\.env\.bak-adopt-\d{4}-\d\d-\d\d", bak[0].name)
        args = tokens((cfgdir / "legacy.args").read_text())
        # every flag-only knob and the path flags, one argv token per line, absolute paths
        assert args[args.index("--followup-s") + 1] == "8"
        assert args[args.index("--wait-speech") + 1] == "4"
        assert Path(args[args.index("--kws-dir") + 1]).is_absolute()
        assert Path(args[args.index("--identity") + 1]).is_absolute()
        assert "--config" not in args
        r.core.write_mirror()
        assert len(list(cfgdir.glob("listen.env.bak-adopt-*"))) == 1        # not kept again
    finally:
        r.close()


def test_every_applied_change_regenerates_both_files(tmp_path, monkeypatch):
    r, cfgdir = mk(tmp_path, monkeypatch)
    try:
        r.core.submit([Edit("agc.mic.target", 0.06), Edit("loop.turns.followup_s", 10.0)], actor="owner", scope="owner")
        r.core.safe_point(True)
        assert kv((cfgdir / "listen.env").read_text())["MIRA_AGC_TARGET"] == "0.06"
        args = tokens((cfgdir / "legacy.args").read_text())
        assert args[args.index("--followup-s") + 1] == "10"
        # an undo is a change too
        r.core.undo(actor="owner", scope="owner")
        r.core.safe_point(True)
        assert kv((cfgdir / "listen.env").read_text())["MIRA_AGC_TARGET"] == "0.05"
        assert tokens((cfgdir / "legacy.args").read_text())[tokens((cfgdir / "legacy.args").read_text()).index("--followup-s") + 1] == "8"
    finally:
        r.close()


def test_a_rebuild_change_lands_in_the_mirror_once_applied(tmp_path, monkeypatch):
    r, cfgdir = mk(tmp_path, monkeypatch)
    try:
        r.core.submit([Edit("wake.kws.threshold", 0.12)], actor="owner", scope="owner")
        r.core.safe_point(True)
        assert kv((cfgdir / "listen.env").read_text())["MIRA_KWS_THRESHOLD"] == "0.12"
    finally:
        r.close()


def test_the_mirror_report_lists_what_legacy_cannot_carry(tmp_path, monkeypatch):
    r, cfgdir = mk(tmp_path, monkeypatch)
    try:
        r.core.submit([Edit("mute.zero.mute_s", 12.0)], actor="owner", scope="owner")
        r.core.safe_point(True)
        keys = {row["key"] for row in r.core.legacy_mirror_report()}
        assert "mute.zero.mute_s" in keys
    finally:
        r.close()


def test_a_run_through_main_writes_only_under_home(tmp_path, monkeypatch, capsys):
    r, cfgdir = mk(tmp_path, monkeypatch)
    r.core.shutdown()
    before = {p for p in tmp_path.rglob("*")}
    rc = ml.main(r.argv)
    assert rc == 0
    new = {p for p in tmp_path.rglob("*")} - before
    assert all(str(p).startswith(str(tmp_path)) for p in new)
    assert {p.name for p in new if p.parent == cfgdir} <= {"listen.env", "legacy.args", "changes.jsonl", "mira.json.lastgood",
                                                             "mira.json.lock", "history", "state"}
    r.close()
