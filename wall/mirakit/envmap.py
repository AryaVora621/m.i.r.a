def explicit_from_argv(parser: argparse.ArgumentParser, argv: Sequence[str]) -> dict:
    """dest -> value for the flags actually present on argv. The parser is copied and every default replaced
    by SUPPRESS, so the namespace holds only what the command line named (a default from the environment or
    from the code is indistinguishable from a typed flag otherwise)."""
    p2 = copy.deepcopy(parser)
    for action in p2._actions:  # argparse has no public way to walk every action
        action.default = argparse.SUPPRESS
    p2._defaults = {}
    p2.exit_on_error = False
    try:
        ns, _unknown = p2.parse_known_args(list(argv))
    except (argparse.ArgumentError, SystemExit):
        return {}
    return dict(vars(ns))


def argv_layer(explicit: Mapping[str, Any], specs: Sequence[PluginSpec]) -> dict[str, Any]:
    """"plugin.key" -> value for knobs whose Knob.arg was named on the command line."""
    out: dict[str, Any] = {}
    for _spec, knob, key in _knobs(specs):
        if knob.arg and knob.arg in explicit and explicit[knob.arg] is not None:
            out[key] = coerce(knob, explicit[knob.arg], key)
            check_bounds(knob, out[key], key)
    return out


def env_layer(env: Mapping[str, str], specs: Sequence[PluginSpec], *, strict: bool = True) -> dict[str, Any]:
    """Knob values from MIRA_* variables. strict=False skips (and logs) a value that does not validate instead
    of raising: the production start must not die over a variable the file layer may be ignoring anyway."""
    out: dict[str, Any] = {}
    for _spec, knob, key in _knobs(specs):
        if knob.env and knob.env in env:
            try:
                out[key] = _from_env_text(knob, env[knob.env], key)
            except _Skip:
                continue
            except ConfigError as exc:
                if strict:
                    raise
                log.warning("ignoring %s: %s", knob.env, exc.message)
    return out


def layer_from_args(args: Any, specs: Sequence[PluginSpec], env: Optional[Mapping[str, str]] = None) -> dict[str, Any]:
    """Knob.arg first, then Knob.env when the arg is None or absent. Defaults are not included: a knob that
    resolves to nothing takes the schema default. This reproduces v1, where MicAGC(target=None) read
    MIRA_AGC_TARGET. `env` defaults to the process environment."""
    env = os.environ if env is None else env
    ns = vars(args) if not isinstance(args, Mapping) else args
    out: dict[str, Any] = {}
    for _spec, knob, key in _knobs(specs):
        value = ns.get(knob.arg) if knob.arg else None
        if value is not None:
            out[key] = coerce(knob, value, key)
            continue
        if knob.env and knob.env in env:
            try:
                out[key] = _from_env_text(knob, env[knob.env], key)
            except _Skip:
                continue
    return out


def _file_skeleton(machine: str, specs: Sequence[PluginSpec], values: Mapping[str, Any]) -> dict:
    """A full file: every core key, every plugin with every key, `values` laid over the defaults."""
    core = core_spec(machine)
    doc: dict[str, Any] = {"format": 1, "machine": machine, "revision": 1,
                           "core": defaults(core), "plugins": {}}
    for spec in specs:
        if spec.name == "core":
            continue
        doc["plugins"][spec.name] = {"enabled": spec.default_enabled, "config": defaults(spec)}
    for key, value in values.items():
        plugin, _, name = key.rpartition(".")
        if plugin == "core":
            doc["core"][name] = value
        elif plugin in doc["plugins"]:
            doc["plugins"][plugin]["config"][name] = value
    doc["core"]["legacy_env"] = "ignore"
    return doc


def adopt_listener(argv: Sequence[str], env: Mapping[str, str], specs: Sequence[PluginSpec],
                   parser: Optional[argparse.ArgumentParser] = None) -> dict:
    """What `mira adopt` writes on the Pi: every key, from the effective legacy values (flag, else env, else
    the code default). The engine stays "legacy" until the owner flips it."""
    values: dict[str, Any] = {}
    values.update(env_layer(env, specs))
    if parser is not None:
        values.update(argv_layer(explicit_from_argv(parser, argv), specs))
    doc = _file_skeleton("listener", specs, values)
    explicit_wav = values.get("source.wav.path")
    if explicit_wav and "source.wav" in doc["plugins"]:
        # --wav FILE swaps the microphone for a file; adopting that would freeze a test run into the deployment
        doc["plugins"]["source.wav"]["config"]["path"] = ""
    return doc


def freeze_here_paths(doc: dict, specs: Sequence[PluginSpec], install_dir: Path) -> list[tuple[str, str, str]]:
    """Rewrite every path knob that still holds `${HERE}` to the absolute file beside the live install, when that
    file exists. `${HERE}` is the folder of the running code, and after the switch that is releases/<id>/, which
    holds code only; the persona, the offline chime and the models stay in the install root, so a default left as
    `${HERE}/x` would silently point at nothing. Returns (key, old, new) for each rewrite."""
    changed: list[tuple[str, str, str]] = []
    for spec in specs:
        body = (doc.get("plugins") or {}).get(spec.name)
        if not body:
            continue
        cfg = body.get("config") or {}
        for knob in spec.knobs:
            value = cfg.get(knob.name)
            if knob.type == "path" and isinstance(value, str) and "${HERE}" in value:
                candidate = os.path.normpath(value.replace("${HERE}", str(install_dir)))
                if os.path.exists(candidate):
                    cfg[knob.name] = candidate
                    changed.append((f"{spec.name}.{knob.name}", value, candidate))
    return changed


def unfrozen_here_paths(doc: dict, specs: Sequence[PluginSpec]) -> list[str]:
    """Keys of path knobs that still hold `${HERE}` after freeze_here_paths (their file is not beside the install)."""
    out = []
    for spec in specs:
        cfg = ((doc.get("plugins") or {}).get(spec.name) or {}).get("config") or {}
        for knob in spec.knobs:
            value = cfg.get(knob.name)
            if knob.type == "path" and isinstance(value, str) and "${HERE}" in value:
                out.append(f"{spec.name}.{knob.name}")
    return out


def _kokoro_voice(model_dir: str, name: str) -> str:
    table = Path(__file__).resolve().parent.parent / "speech_plugins" / "voices" / f"{model_dir}.json"
    try:
        data = json.loads(table.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return f"{model_dir}#{name}"
    names = data.get("speaker_names") or data.get("speakers") or data.get("names") or []
    if isinstance(names, Mapping):
        names = list(names)
    if name in names:
        return f"{model_dir}#{name}"
    for n in names:
        if isinstance(n, str) and n.split("_", 1)[-1] == name:
            return f"{model_dir}#{n}"
    return f"{model_dir}#{name}"


def tts_voice_from_env(env: Mapping[str, str]) -> str:
    """MIRA_TTS_DIR plus MIRA_TTS_VOICE as one voice id. Piper gives "<dir>#0" (the speaker is the model's
    only one, the name is only a label in v1); Kokoro looks the name up in the committed speaker table."""
    model_dir = os.path.basename(env.get("MIRA_TTS_DIR", "vits-piper-en_US-amy-medium").rstrip("/"))
    voice = env.get("MIRA_TTS_VOICE", "amy")
    if model_dir.startswith("kokoro"):
        return _kokoro_voice(model_dir, voice)
    return f"{model_dir}#0"


def adopt_speech(plist_path: Any, specs: Sequence[PluginSpec]) -> dict:
    """The mini's file from the LaunchAgent plist (the live service's environment and launchd keys)."""
    with open(plist_path, "rb") as fh:
        plist = plistlib.load(fh)
    env = {str(k): str(v) for k, v in (plist.get("EnvironmentVariables") or {}).items()}
    values = env_layer(env, specs)
    # v1: TTS_THREADS defaults to MIRA_THREADS when its own variable is absent
    if "MIRA_TTS_THREADS" not in env and "MIRA_THREADS" in env and any(
            k == "tts.engine.threads" for _s, _k, k in _knobs(specs)):
        values["tts.engine.threads"] = int(env["MIRA_THREADS"])
    if any(k == "tts.engine.voice" for _s, _k, k in _knobs(specs)):
        values["tts.engine.voice"] = tts_voice_from_env(env)
    if "Nice" in plist:
        values["core.unit_nice"] = int(plist["Nice"])
    if "ThrottleInterval" in plist:
        values["core.unit_throttle_s"] = int(plist["ThrottleInterval"])
    if "KeepAlive" in plist:
        values["core.unit_keep_alive"] = bool(plist["KeepAlive"])
    return _file_skeleton("speech", specs, values)


