"""Mapping between the v1 world (argv flags, MIRA_* environment, the LaunchAgent plist) and knobs (spec 2.4.1,
2.4.6, 2.5.6). Stdlib only.

All keys here are dotted "plugin.key". Nothing in this module reads or writes the real environment except
through the `env` mapping it is handed, so tests and `mira adopt` stay deterministic.
"""
from __future__ import annotations

import argparse
import copy
import json
import os
import logging
import plistlib
from pathlib import Path
from typing import Any, Mapping, Optional, Sequence

from .plugin import ConfigError, Knob, PluginSpec
from .schema import coerce, check_bounds, core_spec, defaults, expand_path, fmt_num

log = logging.getLogger("mira.envmap")

ENV_HEADER = "# generated by mirakit from mira.json; edit with mira set"

# The path flags the legacy listener resolves relative to its own folder, so the mirror always passes them
# absolute (2.5.6). Flag to "plugin.key".
PATH_FLAGS = {
    "--kws-dir": "wake.kws.kws_dir",
    "--vad-model": "vad.silero.model",
    "--speech-token-file": "speech.link.token_file",
    "--hermes-key-file": "brain.hermes.key_file",
    "--voice-token-file": "reporter.agentos.token_file",
    "--music-auth-file": "intent.music.auth_file",
    "--identity": "persona.file.path",
    "--chime": "playback.miraaudio.chime",
}


def arg_attr(spec: PluginSpec, knob: Knob) -> Optional[str]:
    """The attribute of the listener's args namespace this knob is kept in sync with. The loop.turns knobs
    that have no legacy flag still live on the namespace under their own name (spec 4.1)."""
    if knob.arg:
        return knob.arg
    if spec.name == "loop.turns":
        return knob.name
    return None


def _knobs(specs: Sequence[PluginSpec]):
    for spec in specs:
        for knob in spec.knobs:
            yield spec, knob, f"{spec.name}.{knob.name}"


def _from_env_text(knob: Knob, raw: str, key: str) -> Any:
    """v1 reads env values as text: MIRA_AGC is off only for "0", MIRA_SPEECH_BIND is a comma list. A set but
    empty variable counts as unset for every type except text."""
    if knob.type == "bool":
        return raw != "0"
    if raw == "" and knob.type not in ("str", "path", "url", "regex", "time_window", "voice", "list[str]"):
        raise _Skip
    value = coerce(knob, raw, key, text=True)
    check_bounds(knob, value, key)
    return value


class _Skip(Exception):
    pass


