"""Generated documentation from the plugin specs (spec 2.4.6, 2.11, 2.12.2, 2.12.3). Stdlib only.

One pass over the `PluginSpec` lists of both machines produces: docs/PLUGINS.md, docs/KNOBS.md,
docs/contracts/schema.generated.json, the Hermes skill references (knobs.md, glossary.md) and the vault
reference body. Output is deterministic (sorted, fixed formatting, no timestamps) so `mira check` can compare
the committed files with a fresh render byte for byte.
"""
from __future__ import annotations

import ast
import importlib
import json
import sys
from pathlib import Path
from typing import Any, Mapping, Optional, Sequence

from mirakit import CONTRACT_VERSION
from mirakit.plugin import Knob, PluginSpec

GENERATED_NOTE = "Generated by `mira docs` from the plugin specs. Do not edit by hand; run `mira docs` instead."
TOPICS = ("voice", "hearing", "timing", "wake", "brain", "wall", "system")
MACHINE_ORDER = {"listener": 0, "speech": 1}

# Generated files under wall/, relative to it. `mira check` compares exactly these.
PLUGINS_MD = "docs/PLUGINS.md"
KNOBS_MD = "docs/KNOBS.md"
SCHEMA_JSON = "docs/contracts/schema.generated.json"
GENERATED_PATHS = (PLUGINS_MD, KNOBS_MD, SCHEMA_JSON)


# --------------------------------------------------------------------------------------------
# loading
# --------------------------------------------------------------------------------------------

def load_specs(root: Path) -> tuple[list[PluginSpec], list[str]]:
    """(specs of both machines, warnings). A package that is not there yet is a warning, not a crash."""
    added = str(root) not in sys.path
    if added:
        sys.path.insert(0, str(root))
    specs: list[PluginSpec] = []
    warnings: list[str] = []
    try:
        for pkg in ("listener_plugins", "speech_plugins"):
            try:
                module = importlib.import_module(pkg)
            except ImportError as exc:
                warnings.append(f"{pkg} not importable: {exc}")
                continue
            specs.extend(module.specs())
    finally:
        if added:
            sys.path.remove(str(root))
    return specs, warnings


def ordered(specs: Sequence[PluginSpec]) -> list[PluginSpec]:
    return sorted(specs, key=lambda s: (MACHINE_ORDER.get(s.machine, 9), s.name))


# --------------------------------------------------------------------------------------------
# formatting helpers
# --------------------------------------------------------------------------------------------

def fmt(value: Any) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, float):
        return f"{value:g}"
    if value is None:
        return "null"
    if isinstance(value, (list, dict)):
        return json.dumps(value, ensure_ascii=False)
    return str(value)


def cell(text: Any) -> str:
    return fmt(text).replace("|", "\\|").replace("\n", " ")


def bounds(k: Knob) -> str:
    if k.type in ("int", "float"):
        lo = "" if k.min is None else fmt(k.min)
        hi = "" if k.max is None else fmt(k.max)
        return f"{lo}..{hi}" if (lo or hi) else ""
    if k.type in ("str", "list[str]", "path", "url") and (k.min is not None or k.max is not None):
        unit = "items" if k.type == "list[str]" else "chars"
        return f"{fmt(k.min if k.min is not None else 0)}..{fmt(k.max) if k.max is not None else ''} {unit}"
    if k.type == "enum" and k.choices:
        return ",".join(k.choices)
    return ""


def agent_range(k: Knob) -> str:
    if k.agent != "bounded":
        return "deny"
    if k.agent_min is None or k.agent_max is None:
        return "bounded"
    step = f" step {fmt(k.agent_step)}" if k.agent_step is not None else ""
    return f"{fmt(k.agent_min)}..{fmt(k.agent_max)}{step}"


def default_text(k: Knob) -> str:
    return "(secret path)" if k.secret and not k.default else fmt(k.default)


def knob_json(k: Knob) -> dict:
    return {
        "name": k.name, "type": k.type, "default": k.default, "description": k.description, "unit": k.unit,
        "min": k.min, "max": k.max, "choices": list(k.choices) if k.choices else None, "applies": k.applies,
        "agent": k.agent, "agent_min": k.agent_min, "agent_max": k.agent_max, "agent_step": k.agent_step,
        "secret": k.secret, "arg": k.arg, "env": k.env, "topic": k.topic, "spoken": k.spoken, "effect": k.effect,
        "phrases": list(k.phrases), "nullable": k.nullable,
    }


def discover_legacy_flags(root: Path) -> Optional[frozenset]:
    """Every long option the frozen v1 listener parser defines, read from its source without importing it (the
    parser needs numpy and sherpa-onnx), or None when `mira_listen_v1.py` is not beside `root`. A loop that builds
    flags from a tuple of names (`--agc-{knob}`) is expanded. `Knob.arg` alone cannot say whether a flag exists:
    namespace-only attributes such as `preroll_chunks` have an arg and no flag."""
    path = Path(root) / "mira_listen_v1.py"
    try:
        tree = ast.parse(path.read_text(encoding="utf-8"))
    except (OSError, SyntaxError):
        return None
    flags: set[str] = set()

    def first_arg(call: ast.Call, loop_names: dict[str, list[str]]) -> list[str]:
        if not call.args:
            return []
        arg = call.args[0]
        if isinstance(arg, ast.Constant) and isinstance(arg.value, str):
            return [arg.value]
        if isinstance(arg, ast.JoinedStr):
            outs = [""]
            for part in arg.values:
                if isinstance(part, ast.Constant):
                    outs = [o + str(part.value) for o in outs]
                elif isinstance(part, ast.FormattedValue) and isinstance(part.value, ast.Name) \
                        and part.value.id in loop_names:
                    outs = [o + name for o in outs for name in loop_names[part.value.id]]
                else:
                    return []
            return outs
        return []

    def visit(node: ast.AST, loop_names: dict[str, list[str]]) -> None:
        if isinstance(node, ast.For) and isinstance(node.target, ast.Name) and isinstance(node.iter, (ast.Tuple, ast.List)):
            names = [e.value for e in node.iter.elts if isinstance(e, ast.Constant) and isinstance(e.value, str)]
            loop_names = {**loop_names, node.target.id: names}
        if isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute) and node.func.attr == "add_argument":
            flags.update(f for f in first_arg(node, loop_names) if f.startswith("--"))
        for child in ast.iter_child_nodes(node):
            visit(child, loop_names)

    visit(tree, {})
    return frozenset(flags)


def legacy_flag(k: Knob, flags: Optional[frozenset] = None) -> str:
    """The v1 flag of a knob: `--<arg with dashes>`, when the v1 parser really has it (`flags` from
    `discover_legacy_flags`; None means unknown, so any knob with an arg is assumed to have one, as envmap does)."""
    if not k.arg or k.arg.startswith("_"):
        return ""
    flag = "--" + k.arg.replace("_", "-")
    return flag if flags is None or flag in flags else ""


