def generated_files(specs: Sequence[PluginSpec], legacy_sources: Optional[Mapping[str, str]] = None,
                    flags: Optional[frozenset] = None) -> dict[str, str]:
    return {PLUGINS_MD: render_plugins_md(specs), KNOBS_MD: render_knobs_md(specs, legacy_sources, flags),
            SCHEMA_JSON: render_schema_json(specs)}


def write_all(root: Path, specs: Sequence[PluginSpec], skill_dir: Optional[Path] = None,
              vault_dir: Optional[Path] = None, legacy_sources: Optional[Mapping[str, str]] = None) -> list[Path]:
    written: list[Path] = []

    def put(path: Path, text: str) -> None:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        written.append(path)

    for rel, text in generated_files(specs, legacy_sources, discover_legacy_flags(root)).items():
        put(root / rel, text)
    if skill_dir is not None:
        put(Path(skill_dir) / "references" / "knobs.md", render_skill_knobs(specs))
        put(Path(skill_dir) / "references" / "glossary.md", render_skill_glossary(specs))
    if vault_dir is not None:
        put(Path(vault_dir) / "Mira Plugin Reference.md", render_vault_reference(specs))
    return written


def stale_files(root: Path, specs: Sequence[PluginSpec], legacy_sources: Optional[Mapping[str, str]] = None) -> list[str]:
    """Relative paths whose committed text differs from a fresh render (missing counts as stale)."""
    stale = []
    for rel, text in generated_files(specs, legacy_sources, discover_legacy_flags(root)).items():
        path = root / rel
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            stale.append(rel)
    return stale
