def render_plugins_md(specs: Sequence[PluginSpec]) -> str:
    lines = ["# Mira plugins", "", f"<!-- {GENERATED_NOTE} -->", "",
             "Every plugin of both machines, with the knobs it owns. Bounds are hard limits for every writer; the "
             "agent column is what Hermes may set by voice (always a trial).", ""]
    current = None
    for spec in ordered(specs):
        if spec.machine != current:
            current = spec.machine
            lines += [f"## Machine: {current}", ""]
        lines += [f"### {spec.name}", "", spec.summary, ""]
        facts = [f"version {spec.version}", f"provides: {', '.join(spec.provides) or 'nothing'}",
                 f"needs: {', '.join(spec.needs) or 'nothing'}"]
        if spec.wants:
            facts.append("wants: " + ", ".join(spec.wants))
        if spec.reads:
            facts.append("reads: " + ", ".join(spec.reads))
        facts.append("required" if spec.required else "optional")
        facts.append("on by default" if spec.default_enabled else "off by default")
        facts.append(f"toggle {spec.toggle}")
        if spec.core:
            facts.append("core slot")
        lines += ["- " + "; ".join(facts), ""]
        if spec.knobs:
            lines += ["| key | type | default | bounds | unit | applies | agent | description |",
                      "|---|---|---|---|---|---|---|---|"]
            for k in spec.knobs:
                lines.append(f"| {k.name} | {k.type} | {cell(default_text(k))} | {cell(bounds(k))} | {cell(k.unit)} | "
                             f"{k.applies} | {agent_range(k)} | {cell(k.description)} |")
            lines.append("")
        else:
            lines += ["No knobs.", ""]
    return "\n".join(lines).rstrip("\n") + "\n"


def render_knobs_md(specs: Sequence[PluginSpec], legacy_sources: Optional[Mapping[str, str]] = None,
                    flags: Optional[frozenset] = None) -> str:
    """One row per knob (2.4.6). `legacy_sources` maps "plugin.key" to the v1 source line of a literal, when known;
    `flags` is the set of real v1 options (see discover_legacy_flags)."""
    sources = legacy_sources or {}
    lines = ["# Mira knobs and where they came from", "", f"<!-- {GENERATED_NOTE} -->", "",
             "| plugin | key | type | default | bounds | unit | applies | agent | legacy env | legacy flag | v1 source |",
             "|---|---|---|---|---|---|---|---|---|---|---|"]
    for spec in ordered(specs):
        for k in spec.knobs:
            key = f"{spec.name}.{k.name}"
            flag = legacy_flag(k, flags)
            src = sources.get(key) or ("literal" if not k.env and not flag else "")
            lines.append(f"| {spec.name} | {k.name} | {k.type} | {cell(default_text(k))} | {cell(bounds(k))} | "
                         f"{cell(k.unit)} | {k.applies} | {agent_range(k)} | {cell(k.env or '')} | "
                         f"{cell(flag)} | {cell(src)} |")
    return "\n".join(lines) + "\n"


def schema_dict(specs: Sequence[PluginSpec]) -> dict:
    machines: dict[str, list] = {}
    for spec in ordered(specs):
        machines.setdefault(spec.machine, []).append({
            "name": spec.name, "kind": spec.kind, "version": spec.version, "summary": spec.summary,
            "provides": list(spec.provides), "needs": list(spec.needs), "wants": list(spec.wants),
            "reads": list(spec.reads), "required": spec.required, "core": spec.core, "toggle": spec.toggle,
            "default_enabled": spec.default_enabled, "knobs": [knob_json(k) for k in spec.knobs],
        })
    return {"contract_version": CONTRACT_VERSION, "machines": machines}


def render_schema_json(specs: Sequence[PluginSpec]) -> str:
    return json.dumps(schema_dict(specs), indent=1, ensure_ascii=False) + "\n"


def _tuned_knobs(specs: Sequence[PluginSpec]) -> list[tuple[PluginSpec, Knob]]:
    return [(s, k) for s in ordered(specs) for k in s.knobs if k.topic or k.phrases or k.agent == "bounded"]


def ladder(k: Knob) -> list[Any]:
    if k.agent != "bounded" or k.type not in ("int", "float") or k.agent_min is None or k.agent_step is None:
        return []
    steps = int(round((k.agent_max - k.agent_min) / k.agent_step))
    values = [round(k.agent_min + i * k.agent_step, 6) for i in range(steps + 1)]
    return [int(v) for v in values] if k.type == "int" else values


def render_skill_knobs(specs: Sequence[PluginSpec]) -> str:
    lines = ["# Knobs Mira can tune (generated)", "", f"<!-- {GENERATED_NOTE} -->", "",
             "Only the bounded rows may be set by voice, one step at a time, always as a ten minute trial. "
             "Owner-only rows need Arya: file the owner command with the owner-tasks tool.", ""]
    rows = _tuned_knobs(specs)
    for topic in TOPICS:
        group = [(s, k) for s, k in rows if k.topic == topic]
        if not group:
            continue
        lines += [f"## {topic}", "", "| key | spoken name | by voice | range | step | steps you can reach | applies | effect |",
                  "|---|---|---|---|---|---|---|---|"]
        for s, k in group:
            key = f"{s.name}.{k.name}"
            if k.agent == "bounded":
                lad = " ".join(fmt(v) for v in ladder(k))
                rng = f"{fmt(k.agent_min)}..{fmt(k.agent_max)} {k.unit}".strip() if k.agent_min is not None else "any usable"
                lines.append(f"| {key} | {cell(k.spoken or k.name.replace('_', ' '))} | yes | {cell(rng)} | "
                             f"{cell(fmt(k.agent_step) if k.agent_step is not None else '')} | {cell(lad)} | "
                             f"{k.applies} | {cell(k.effect)} |")
            else:
                lines.append(f"| {key} | {cell(k.spoken or k.name.replace('_', ' '))} | owner only | | | | "
                             f"{k.applies} | {cell(k.effect)} |")
        lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


def render_skill_glossary(specs: Sequence[PluginSpec]) -> str:
    lines = ["# Glossary: what the owner says, what it means (generated)", "", f"<!-- {GENERATED_NOTE} -->", "",
             "| owner says | key | spoken name | effect when raised | by voice |", "|---|---|---|---|---|"]
    rows = []
    for s, k in _tuned_knobs(specs):
        for phrase in k.phrases:
            rows.append((phrase, f"{s.name}.{k.name}", k, s))
    rows.sort(key=lambda r: (r[1], r[0]))
    for phrase, key, k, _ in rows:
        voice_range = (f"{fmt(k.agent_min)}..{fmt(k.agent_max)} step {fmt(k.agent_step)}"
                       if k.agent == "bounded" and k.agent_min is not None else
                       ("yes" if k.agent == "bounded" else "owner only"))
        lines.append(f"| \"{cell(phrase)}\" | {key} | {cell(k.spoken or k.name.replace('_', ' '))} | "
                     f"{cell(k.effect)} | {voice_range} |")
    return "\n".join(lines) + "\n"


def render_vault_reference(specs: Sequence[PluginSpec]) -> str:
    """Body of the vault note `Mira Plugin Reference`: compact, no secrets (token paths are knob defaults only)."""
    lines = ["# Mira Plugin Reference", "", f"> {GENERATED_NOTE}", "",
             "Mira's wall voice is a set of plugins on two machines: the listener on the Pi and the speech server on "
             "the Mac mini. Settings live in `mira.json` (Pi) and `speech.json` (mini); change them with `mira set`.",
             ""]
    current = None
    for spec in ordered(specs):
        if spec.machine != current:
            current = spec.machine
            lines += [f"## {current}", ""]
        lines.append(f"### {spec.name} (v{spec.version})")
        lines += ["", spec.summary, ""]
        for k in spec.knobs:
            lines.append(f"- `{k.name}` ({k.type}, default {fmt(default_text(k))}"
                         f"{', ' + k.unit if k.unit else ''}{', ' + bounds(k) if bounds(k) else ''}; {k.applies}; "
                         f"agent {agent_range(k)}): {k.description}")
        lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


def tuning_guide_data(specs: Sequence[PluginSpec], topic: str) -> dict:
    """Static 2.7.3 tuning guide: the same shape the API returns, with each knob's default standing in for the
    live value. Generated from the schemas, so nothing is copied by hand."""
    knobs, owner_only = [], []
    for s in ordered(specs):
        for k in s.knobs:
            if k.topic != topic:
                continue
            key = f"{s.name}.{k.name}"
            if k.agent == "bounded":
                knobs.append({"key": key, "spoken": k.spoken or k.name.replace("_", " "), "value": k.default,
                              "unit": k.unit, "settable_by_voice": True, "agent_min": k.agent_min,
                              "agent_max": k.agent_max, "agent_step": k.agent_step, "ladder": ladder(k),
                              "effect": k.effect, "phrases": list(k.phrases), "applies": k.applies})
            else:
                owner_only.append({"key": key, "spoken": k.spoken or k.name.replace("_", " "),
                                   "why": "Only the owner may change this setting.",
                                   "owner_command": f"mira set {key}={fmt(k.default)} --trial 600"})
    return {"topic": topic, "knobs": knobs, "owner_only": owner_only}


